/// Decode a hex literal (with or without "0x") into a 4-byte selector.
fn sel(comptime hex_str: []const u8) [4]u8 {
    return hex.hexToBytesFixed(4, hex_str) catch unreachable;
}

/// Decode a hex literal into a 20-byte address.
fn addr(comptime hex_str: []const u8) [20]u8 {
    return hex.hexToBytesFixed(20, hex_str) catch unreachable;
}

/// Decode a hex literal into a 32-byte word (e.g. a blockhash).
fn word32(comptime hex_str: []const u8) [32]u8 {
    return hex.hexToBytesFixed(32, hex_str) catch unreachable;
}

/// Decode a "0x..."-prefixed calldata hex literal into a fixed-size byte
/// array sized at comptime from the literal's length.
fn fixtureBytes(comptime hex_str: []const u8) [(hex_str.len - 2) / 2]u8 {
    @setEvalBranchQuota(1_000_000);
    return hex.hexToBytesFixed((hex_str.len - 2) / 2, hex_str) catch unreachable;
}

/// Pack a Uniswap V3 `token(20) fee(3) token(20) ...` path from tokens and
/// per-hop fees. Caller frees with `allocator.free`.
fn packV3Path(allocator: std.mem.Allocator, tokens: []const [20]u8, fees: []const u24) ![]u8 {
    std.debug.assert(tokens.len == fees.len + 1);
    var buf: std.ArrayList(u8) = .empty;
    errdefer buf.deinit(allocator);
    for (tokens, 0..) |t, i| {
        try buf.appendSlice(allocator, &t);
        if (i < fees.len) {
            const f = fees[i];
            try buf.append(allocator, @intCast((f >> 16) & 0xff));
            try buf.append(allocator, @intCast((f >> 8) & 0xff));
            try buf.append(allocator, @intCast(f & 0xff));
        }
    }
    return buf.toOwnedSlice(allocator);
}

/// Raw big-endian byte-buffer builder for hand-crafted (possibly malformed)
/// calldata that `abi_encode`'s clean encoder cannot produce (dirty padding,
/// out-of-range offsets, mismatched array lengths, ...).
const Builder = struct {
    buf: std.ArrayList(u8) = .empty,
    allocator: std.mem.Allocator,

    fn init(allocator: std.mem.Allocator) Builder {
        return .{ .allocator = allocator };
    }
    fn deinit(self: *Builder) void {
        self.buf.deinit(self.allocator);
    }
    fn sel4(self: *Builder, s: [4]u8) !void {
        try self.buf.appendSlice(self.allocator, &s);
    }
    /// A clean, correctly zero-padded uint256 word.
    fn w(self: *Builder, v: u256) !void {
        try self.buf.appendSlice(self.allocator, &uint256.toBigEndianBytes(v));
    }
    /// A clean, correctly zero-padded address word.
    fn wAddr(self: *Builder, a: [20]u8) !void {
        var word: [32]u8 = @splat(0);
        @memcpy(word[12..32], &a);
        try self.buf.appendSlice(self.allocator, &word);
    }
    /// An arbitrary 32-byte word, verbatim (for dirty bits/padding attacks).
    fn wRaw(self: *Builder, word: [32]u8) !void {
        try self.buf.appendSlice(self.allocator, &word);
    }
    fn raw(self: *Builder, bytes: []const u8) !void {
        try self.buf.appendSlice(self.allocator, bytes);
    }
    fn padZero(self: *Builder, n: usize) !void {
        try self.buf.appendNTimes(self.allocator, 0, n);
    }
    fn ownedSlice(self: *Builder) ![]u8 {
        return self.buf.toOwnedSlice(self.allocator);
    }
};

// ============================================================================
// Infallibility walkers
// ============================================================================
//
// The contract (spec section 4): if `decode` returns non-null, every
// accessor and iterator is infallible. These walkers exercise all of them so
// AT7's fuzzing actually reaches every code path, not just the top-level
// union tag.

fn walkAddressPath(p: c.AddressPath) void {
    const n = p.len();
    var i: usize = 0;
    while (i < n) : (i += 1) _ = p.get(i);
    // R1: every address[] swap path decode() returns has at least 2
    // elements, so first()/last() are valid on any non-null decode. No
    // `n > 0` guard: calling them unconditionally is exactly the contract
    // this walker is meant to exercise.
    _ = p.first();
    _ = p.last();
}

fn walkV3Path(p: c.V3Path) void {
    const n = p.hops();
    var i: usize = 0;
    while (i < n) : (i += 1) _ = p.hop(i);
    _ = p.first();
    _ = p.last();
}

fn walkU256Array(a: c.U256Array) void {
    const n = a.len();
    var i: usize = 0;
    while (i < n) : (i += 1) _ = a.get(i);
}

fn walkCommand(cmd: c.Command) void {
    switch (cmd.payload) {
        .v3_swap_exact_in => |p| {
            walkV3Path(p.path);
            if (p.min_hop_price_x36) |arr| walkU256Array(arr);
        },
        .v3_swap_exact_out => |p| {
            walkV3Path(p.path);
            if (p.min_hop_price_x36) |arr| walkU256Array(arr);
        },
        .v2_swap_exact_in => |p| {
            walkAddressPath(p.path);
            if (p.min_hop_price_x36) |arr| walkU256Array(arr);
        },
        .v2_swap_exact_out => |p| {
            walkAddressPath(p.path);
            if (p.min_hop_price_x36) |arr| walkU256Array(arr);
        },
        .sweep, .transfer, .pay_portion, .wrap_eth, .unwrap_weth, .other => {},
    }
}

fn walkDecoded(d: c.Decoded) void {
    switch (d) {
        .v2_swap_exact_tokens_for_tokens,
        .v2_swap_exact_tokens_for_eth,
        .v2_swap_exact_tokens_for_tokens_fot,
        .v2_swap_exact_tokens_for_eth_fot,
        .swap_router02_swap_exact_tokens_for_tokens,
        => |s| walkAddressPath(s.path),
        .v2_swap_tokens_for_exact_tokens,
        .v2_swap_tokens_for_exact_eth,
        .swap_router02_swap_tokens_for_exact_tokens,
        => |s| walkAddressPath(s.path),
        .v2_swap_exact_eth_for_tokens, .v2_swap_exact_eth_for_tokens_fot => |s| walkAddressPath(s.path),
        .v2_swap_eth_for_exact_tokens => |s| walkAddressPath(s.path),
        .v3_exact_input => |s| walkV3Path(s.path),
        .v3_exact_output => |s| walkV3Path(s.path),
        .v3_exact_input_single, .v3_exact_output_single => {},
        .multicall => |m| {
            _ = m.len();
            var it = m.iterator();
            while (it.next()) |call| {
                switch (call) {
                    .swap => |inner| walkDecoded(inner),
                    .other => {},
                }
            }
        },
        .universal_router_execute => |ur| {
            var it = ur.iterator();
            while (it.next()) |cmd| walkCommand(cmd);
        },
    }
}

